const Context = createContext();
export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    try {
      return localStorage.getItem('sevasignal-language') === 'hi' ? 'hi' : 'en';
    } catch {
      return 'en';
    }
  });
  useEffect(() => {
    document.documentElement.lang = language;
    try {
      localStorage.setItem('sevasignal-language', language);
    } catch {}
  }, [language]);
  const t = (key) => (language === 'hi' ? hi[key] : en[key]) || en[key] || key;
  const name = (item) => (language === 'hi' && item?.name_hi ? item.name_hi : item?.name);
  return <Context.Provider value={{ language, setLanguage, t, name }}>{children}</Context.Provider>;
}
export const useLanguage = () => useContext(Context);
